#Requires -Version 7.0
<#
.SYNOPSIS
  Emit Novolis.PackageToProject.props mapping packable PackageId → sibling .csproj.

.DESCRIPTION
  Scans novolis-*/**/*.csproj for IsPackable=true, reads PackageId (fallback: filename),
  and writes an MSBuild item list used by Novolis.ProjectReferenceMode.targets.

.PARAMETER WorkspaceRoot
  Novolis workspace root (parent of novolis-governance).

.PARAMETER OutputPath
  Props file to write. Defaults to build/generated/Novolis.PackageToProject.props next to this script.
#>
[CmdletBinding()]
param(
    [string]$WorkspaceRoot,
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $WorkspaceRoot) {
    $WorkspaceRoot = Split-Path -Parent (Split-Path -Parent $scriptDir)
}
if (-not (Test-Path -PathType Container $WorkspaceRoot)) {
    throw "Workspace root does not exist: $WorkspaceRoot"
}

if (-not $OutputPath) {
    $OutputPath = Join-Path $scriptDir 'generated\Novolis.PackageToProject.props'
}

$excludeRepo = [regex]'workflows|governance|registry|dogfooding|installer|experimental|smoketest|template-dotnet'

$entries = [System.Collections.Generic.List[object]]::new()
$seen = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)

Get-ChildItem $WorkspaceRoot -Directory -Filter 'novolis-*' |
    Where-Object { $_.Name -notmatch $excludeRepo } |
    ForEach-Object {
        $repoName = $_.Name
        Get-ChildItem $_.FullName -Recurse -Filter '*.csproj' -ErrorAction SilentlyContinue |
            Where-Object { $_.FullName -notmatch '[\\/](obj|bin)[\\/]' } |
            ForEach-Object {
                $text = Get-Content $_.FullName -Raw
                if ($text -notmatch '<IsPackable>\s*true\s*</IsPackable>') { return }

                $packageId = if ($text -match '<PackageId>\s*([^<]+?)\s*</PackageId>') {
                    $Matches[1].Trim()
                }
                else {
                    [IO.Path]::GetFileNameWithoutExtension($_.Name)
                }

                if (-not $seen.Add($packageId)) {
                    throw "Duplicate PackageId '$packageId' (also in $repoName). Fix before regenerating map."
                }

                $relFromWorkspace = $_.FullName.Substring($WorkspaceRoot.Length).TrimStart('\', '/')
                $relFromWorkspace = $relFromWorkspace -replace '/', '\'

                $entries.Add([pscustomobject]@{
                        PackageId = $packageId
                        RelPath   = $relFromWorkspace
                        Repo      = $repoName
                    }) | Out-Null
            }
    }

$sorted = $entries | Sort-Object PackageId
$outDir = Split-Path -Parent $OutputPath
if (-not (Test-Path -PathType Container $outDir)) {
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('<!--')
[void]$sb.AppendLine('  AUTO-GENERATED by Generate-PackageToProjectMap.ps1 — do not edit.')
[void]$sb.AppendLine('  Regenerate: pwsh -File novolis-governance/build/Generate-Platform-Slnx.ps1')
[void]$sb.AppendLine('  or:         pwsh -File novolis-governance/build/Generate-PackageToProjectMap.ps1')
[void]$sb.AppendLine('-->')
[void]$sb.AppendLine('<Project>')
[void]$sb.AppendLine('  <ItemGroup>')

foreach ($e in $sorted) {
    $path = $e.RelPath -replace '\\', '\'
    [void]$sb.AppendLine("    <NovolisPackageProject Include=`"$($e.PackageId)`">")
    [void]$sb.AppendLine("      <ProjectPath>`$(NovolisWorkspaceRoot)$path</ProjectPath>")
    [void]$sb.AppendLine('    </NovolisPackageProject>')
}

[void]$sb.AppendLine('  </ItemGroup>')
[void]$sb.AppendLine('</Project>')

Set-Content -Path $OutputPath -Value $sb.ToString().TrimEnd() -Encoding utf8NoBOM

Write-Host "Wrote $($sorted.Count) package→project entries to $OutputPath"
return @{
    OutputPath = $OutputPath
    Count      = $sorted.Count
}
